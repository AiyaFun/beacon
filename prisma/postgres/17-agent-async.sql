-- 17 · AI 执行改后台跑：挂起（在等什么）与执行租约（谁在跑）（2026-08-21）
--
-- 【为什么要这两列】在此之前一次执行是**同步**跑完的：用户点「开始执行」的那个请求
-- 里模型想完、工具跑完、答案写完才返回。于是三件事做不到：
--   ① 派完关页走人——关掉页面等于把执行掐断在半路；
--   ② 派活给浏览器插件后接着往下推理——插件要等用户下次打开浏览器，同步等不了；
--   ③ 长活不撞请求超时。
-- 改成「建记录 → 后台跑」之后，就必须回答两个新问题：**它停在等什么**、**谁在跑它**。
--
-- waitingOn：在等一件什么外部的事，格式 `<类型>:<id>`，目前只有 `browser:<BrowserTask.id>`。
--   那件事有结果了（完成/失败/过期/取消）就按这一列反查该叫醒谁。
--   刻意不是外键：等待对象将来会有别的类型（工作流、人工），外键会把它钉死在一张表上。
--
-- leaseUntil：后台跑这次运行的进程持有的租约。到期没续 = 那个进程没了，别人可以接手。
--   没有它，「确认」点两下、或插件回执重投一次，同一次运行就会被两处同时往前推
--   ——两条推理线交替写同一行 messages，最后是一份自相矛盾的对话和重复执行的工具。
--
-- 两列都可空：存量行 NULL = 「没在等什么」「没人在跑」，正是它们的真实状态。
-- 幂等：IF NOT EXISTS。
ALTER TABLE "AgentRun" ADD COLUMN IF NOT EXISTS "waitingOn" TEXT;
ALTER TABLE "AgentRun" ADD COLUMN IF NOT EXISTS "leaseUntil" TIMESTAMP(3);

-- 叫醒时按「在等哪件事」反查（一件事可能有多次运行在等它）。
CREATE INDEX IF NOT EXISTS "AgentRun_waitingOn_idx" ON "AgentRun"("waitingOn");
