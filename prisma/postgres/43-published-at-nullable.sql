-- 2026-08-30 PublishRecord.publishedAt 改为可空。
--
-- ── 为什么 ──
-- lib/ingest/own-post.ts 的新建分支原来写的是 `publishedAt: post.publishedAt ?? new Date()`，
-- 把**插件回填那一刻**当成发布时间存进库，而库里没有任何字段标记这是猜的。
-- 小红书笔记页、B站视频页、YouTube 播放页/频道页的解析器**结构上就不产出**这个字段，
-- 而「这是我的作品 · 回填数据看板」按钮在这几个页面上都是露出的——所以这是常态不是边角。
--
-- 后果三处、全部静默（用户只会看到一个错的结论，不会看到报错）：
--   ① /data 的「发布时段分析」把这些作品全归到用户点回填的那个时辰，
--      页面上印出「你的最佳发布时段是 深夜/凌晨（N 条 · 均播 xxx）」；
--   ② 逐日曲线的 D+0 携带这条作品**全生命周期**的累计播放 → 判成「首日爆发型」写进复盘；
--   ③ 拿这个 D+0 去比同窗基线，ratio ≥ 2 就发「🚀 爆款加速」站内通知 + 推送 + 短信，
--      对一条其实发了三个月的老作品。
--
-- 同一个函数 12 行之下的台账注释正写着「回填时间不能冒充发布时间，那正是 0.4.7 之前
-- 把发布时间写成回填当天所犯的错」——台账那条路传的是 `?? null`，落库这条路却补了 now()。
--
-- ── 存量数据怎么办 ──
-- **不动**。已经写进去的那些分不出「真的是那天发的」和「那天回填的」，
-- 猜着清一遍只会把一批真数据也清掉。这份迁移只保证**从此以后**不再编造；
-- 存量会随着用户下次回填带上真实时间而自愈（applyMetrics 的 fillDate 只往早改，见那里的说明）。
--
-- 幂等，可重复执行。

ALTER TABLE beacon."PublishRecord" ALTER COLUMN "publishedAt" DROP NOT NULL;

-- 默认值也去掉：留着它，任何忘了传这个字段的写入路径又会被悄悄补成 now()，
-- 而那正是这次要修的形状。
ALTER TABLE beacon."PublishRecord" ALTER COLUMN "publishedAt" DROP DEFAULT;
