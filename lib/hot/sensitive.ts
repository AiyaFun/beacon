// 模式层：伤亡人数是**数字**，穷举不了（「致3伤」「2人遇难」「造成12人受伤」），交给正则。
const SENSITIVE_PATTERNS: { category: string; label: string; re: RegExp }[] = [
  { category: 'disaster', label: '致N死伤', re: /致\s*\d+\s*(人)?\s*(死|伤|亡)/ },
  { category: 'disaster', label: 'N人死伤', re: /\d+\s*(人|名)\s*(死亡|遇难|受伤|失踪|被困)/ },
];

export type SensitiveHit = { word: string; category: string };

// 词库粗筛：纯函数、无 IO、无 key 依赖 —— 它是这道护栏永远在线的那一半。
export function sensitiveHits(title: string): SensitiveHit[] {
  const t = title.toLowerCase();
  const hits: SensitiveHit[] = [];
  for (const g of SENSITIVE_LEXICON) {
    for (const w of g.words) if (t.includes(w)) hits.push({ word: w, category: g.category });
  }
  for (const p of SENSITIVE_PATTERNS) {
    if (p.re.test(t)) hits.push({ word: p.label, category: p.category });
  }
  return hits;
}

export function isSensitiveTitle(title: string): boolean {
  return sensitiveHits(title).length > 0;
}

