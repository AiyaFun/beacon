//    /hotlists 的 SEO 文案上一轮就是因为写死「9 大平台」并点名快手/小红书/微信被修过一回。
//    写死的数字不会报错、不会变红，只会在某一天变成一句对着搜索引擎说的假话。
//    用户 2026-09-17 明确拍板：「按照实际的为准」。

