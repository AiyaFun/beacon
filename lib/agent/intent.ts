// ── 这句话是「问它一下」还是「让它去做」 ────────────────────────────────────
//
// 【为什么需要它】助手此前把这个判断甩给了用户：进页面先在「对话（只答不动手）」和
// 「执行（AI 直接操作系统）」之间选一个。但用户不知道自己那句话属于哪一类——
// 「帮我想 3 条选题」既能当聊天答、也能真的落库。让用户先做一道系统内部的分类题，
// 是把实现细节当成了产品概念。
//
// 现在的做法：默认走对话（流式、便宜、不动数据），答完之后**如果这句话像是让它去做**，
// 就在回答下面给一个「让它直接去做」按钮，点了才真的开一次执行。
//
// 【为什么用本地规则而不是让模型自己吐个标记】模型会把标记、占位符、元信息原样抄给
// 用户（[[beacon-prompt-leak-lessons]] 里踩了三次），而这里的收益只是一个按钮显不显示——
// 为它引入一条「模型输出里混着控制信号」的通道不划算。纯函数、零成本、可单测。
//
// 【误判的代价不对称，所以往召回偏】多显示一个按钮＝用户忽略它；少显示＝那条路没了。
// 但也不能全都显示——每条回答后面都挂个「要我去做吗」就成了背景噪音，
// 于是纯咨询句（怎么/为什么/是不是…）明确排除。

/**
 * 动作词。**一律用两字以上的组合**——单字会串台，而串台在这里是静默的：
 *   「建」撞「建议」（给我一些建议）、「采」撞「采纳」、「排」撞「排名」、
 *   「加」撞「参加/更加」。同 [[beacon-metric-parsing-pitfalls]] 的子串陷阱。
 */
const ACTION_PATTERNS = [
  // 建东西
  '新建', '创建', '建一个', '建个', '建一篇', '建一条', '起稿', '起个稿',
  '写一篇', '写一条', '写篇', '写个', '写一版', '生成', '出一版', '出一稿',
  // 采数据
  '采集', '采一下', '采一遍', '去采', '采数据', '抓一下', '抓一遍', '回填', '刷新数据', '更新数据',
  // 跑东西
  '跑一遍', '跑一下', '跑一次', '跑起来', '执行一下', '派它', '派一个', '派个',
  // 加东西
  '添加', '加一个', '加个', '加进', '加到', '收进',
  // 发东西
  '发布', '发出去', '排发布', '安排发布',
  // 整理
  '整理成', '汇总成', '导出',
];

/**
 * 「动词 + 数量」这一族。中文里最常见的派活说法是「帮我想 3 个选题」「来 5 条」，
 * 而它的动词（想/来/出）单独看全是高频误伤词（我想知道 / 来源 / 出现），
 * 只有**紧跟着数量**时才立得住。数字与量词之间允许空格（用户经常打「想 3 个」）。
 */
const ACTION_REGEXES = [/(想|来|出|给我|推荐|整理|汇总)\s*\d+\s*[个条组篇张份]/];

/**
 * 纯咨询句的标志。命中这些说明用户在问「怎么回事」，不是在派活。
 *
 * 【为什么把「什么」和「吗」这种大词也收进来】它们几乎必然出现在问句里，而漏掉的代价
 * 是实打实的误判：「发布之前要注意什么」命中了动作词「发布」，只挡「什么是」是挡不住的；
 * 「草稿能不能自动创建」同理（第一版只写了「是不是/有没有/行不行」，恰恰漏了最常用的
 * 「能不能」）。误伤的那一侧有委派词兜着——「帮我发布吗」仍然算派活。
 */
const QUESTION_PATTERNS = [
  '怎么', '如何', '为啥', '什么', '吗',
  '能不能', '可不可以', '可以吗', '要不要', '该不该', '是不是', '有没有',
  '哪个好', '区别', '值不值', '好不好', '行不行', '建议',
];

/**
 * 委派词。它比问句标志更强——「能不能帮我建个草稿」是问句形式的**派活**，
 * 用户要的就是让它去做。只看问号会把这种最典型的说法整类漏掉。
 */
const DELEGATE_PATTERNS = ['帮我', '替我', '给我', '你去', '直接去', '现在就', '马上'];

const hit = (text: string, list: readonly string[]) => list.some((p) => text.includes(p));
const hitRe = (text: string, list: readonly RegExp[]) => list.some((re) => re.test(text));

/**
 * 这句话像不像「让它去做」。
 *
 * 判定次序（顺序不能换）：
 *   ① 没有任何动作词 → 一定不是派活。
 *   ② 有动作词 + 有委派词 → 是（「能不能帮我建个草稿」走这条）。
 *   ③ 有动作词但整句是咨询口吻 → 不是（「草稿怎么创建」「有没有必要发布」）。
 *   ④ 其余有动作词的 → 是。
 */
export function looksActionable(text: string): boolean {
  const t = (text ?? '').trim();
  if (t.length < 2 || t.length > 2000) return false;
  if (!hit(t, ACTION_PATTERNS) && !hitRe(t, ACTION_REGEXES)) return false;
  if (hit(t, DELEGATE_PATTERNS)) return true;
  if (hit(t, QUESTION_PATTERNS)) return false;
  return true;
}

/**
 * 强委派：这句话不只是「像派活」，而是**明说了要它去执行**。
 *
 * 2026-08-26 真机反馈：「帮我去执行一下今天的采集」在对话侧得到一大篇计划文字，
 * 用户的原话是「并没办法去执行」——对这种句子，先答一篇再给按钮是绕路。
 * 命中这里的，输入框直接把话移交到「让它去做」预填（仍然要用户按开始才真跑、
 * 才花配额——自动开跑的红线不动，见 tests/shell-modes.test.ts 的 ?goal= 守卫）。
 * 词表刻意窄：只收「去执行/执行一下」这种不可能是提问的说法，宁可漏（漏了还有
 * 答后按钮兜底），不可误收（误收会把想聊的人硬拽进执行面板）。
 */
const STRONG_DELEGATE = /(帮我去|替我去|去执行|执行一下|直接执行|直接去做)/;

/**
 * 查询系统数据的说法。「给我今天的选题」在对话侧只能得到编造（那边没工具），
 * 真数据在执行侧的 list_topics/list_drafts……这类句子也直通执行侧。
 * 结构=（取数动词 或 我的/今天的这类归属词）+ 系统数据名词，两段都命中才算——
 * 只写名词会把「选题是什么意思」也拽过去。
 */
const DATA_VERBS = /(给我|看看|查查|查一下|列一下|拉一下|汇总|看下|要)/;
const DATA_OWN = /(我的|我今天|今天的|本周的|最近的|当前的)/;
const DATA_NOUNS = /(选题|推荐|草稿|数据|竞对|对标|热点|任务|作战|发布计划|表现)/;

export function wantsExecution(text: string): boolean {
  const t = (text ?? '').trim();
  if (t.length < 4 || t.length > 2000) return false;
  // 查数据类：动词/归属 + 系统名词，且不是疑问口吻（「我的选题怎么没了」照旧对话）
  if (DATA_NOUNS.test(t) && (DATA_VERBS.test(t) || DATA_OWN.test(t))
      && !QUESTION_PATTERNS.some((p) => t.includes(p))) {
    return true;
  }
  // 强委派短语本身就是执行语（「去执行/执行一下/直接去做」没有提问用法），
  // 不再要求命中动作词表——「直接去做今天的选题推荐」的「推荐」不在动作词表里，
  // && looksActionable 会把这类句子漏掉。只需挡住疑问口吻
  //（「执行一下是什么意思」照旧走对话）。
  return STRONG_DELEGATE.test(t) && !QUESTION_PATTERNS.some((p) => t.includes(p));
}
