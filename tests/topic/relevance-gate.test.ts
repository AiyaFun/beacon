import { describe, it, expect } from 'vitest';
import { isSensitiveTitle, SENSITIVE_RULES_VERSION } from '@/lib/hot/sensitive';

// 跑题/时政选题不许进「今日推荐」。
//
// 真机 2026-07-30，一个「家庭理财与保险避坑」账号（受众 28-40 岁新手爸妈）收到的推荐里有：
//   · 「唐朝不存在？伪史论歪风一定要刹住」  切入角「从保险与理财角度探讨伪史论对家庭资产规划的长远影响」 人设匹配 85
//   · 「中共中央召开党外人士座谈会」        切入角「解读对普通家庭理财和民生政策的影响」               人设匹配 90
// 高热度时政条目靠 heat 权重挤进精排（coarseRank 里 heat 占 0.30），再被「差异化切入角是强制字段」
// 这条指令逼出一座拉郎配的桥和虚高的 personaFit。
//
// 两道独立的闸：
//   1. 词库层（本文件测的这部分）——个人号碰时政是限流/封号风险，不是「相关性差」这么轻，
//      所以该拦在进候选池之前，恒定生效、不依赖 LLM 可用性；
//   2. 精排层（finePrompt 的 relevant 字段）——通用兜底，覆盖词库天然抓不住的「泛泛谈启示」类硬凑。

describe('时政类热点不进候选池（词库层）', () => {
  it('真机漏过去的两条现在都拦得住', () => {
    expect(isSensitiveTitle('唐朝不存在？伪史论歪风一定要刹住')).toBe(true);
    expect(isSensitiveTitle('中共中央召开党外人士座谈会')).toBe(true);
  });

  it('同类时政词条一并覆盖', () => {
    for (const title of [
      '中央军委举行晋衔仪式',
      '全国两会前瞻：今年的民生议题',
      '二十大报告解读',
      '十四五规划收官之年',
      '三中全会公报发布',
      '统一战线工作会议召开',
      '历史虚无主义要不得',
    ]) {
      expect(isSensitiveTitle(title), `未拦住：${title}`).toBe(true);
    }
  });

  // 🔒 中文没有词边界，这里是纯 includes——短词必然踩子串误杀。
  // 下面六条全部是第一版真踩过的坑（写这个测试时才发现，六个新词六个坑），
  // 修法是一律换成无歧义的长形式。误杀比漏标更快毁掉产品：推荐池会被日常词条清空。
  it('🔒 不误杀创作者的正常选题（子串碰撞回归）', () => {
    for (const title of [
      '中央空调怎么选不踩坑',      // 中央 ← 早有先例，光杆「中央」本就不收
      '两会员制超市对比测评',      // 两会 → 已改为「全国两会」
      '组织部分学生参观博物馆',    // 组织部 → 已改为「中组部」
      '全球二十大最美海岛',        // 二十大 → 已改为「二十大报告 / 二十大精神」
      '公司宣传部门团建',          // 宣传部 → 已改为「中宣部」
      '集中全会员优惠',            // 中全会 → 已改为「三中全会」等具名形式
      '统一战线上的品牌打法',      // 统一战线 → 已改为「统一战线工作」
      '家庭理财新手最容易踩的坑',
      '小红书起号第一周做什么',
      '副业月入过万是真的吗',
    ]) {
      expect(isSensitiveTitle(title), `误杀了：${title}`).toBe(false);
    }
  });

  it('规则版本已随词库变更 bump（F1-4 AC③ 可审计）', () => {
    expect(SENSITIVE_RULES_VERSION).not.toBe('2026.07');
    expect(SENSITIVE_RULES_VERSION).toMatch(/^\d{4}\.\d{2}/);
  });
});
